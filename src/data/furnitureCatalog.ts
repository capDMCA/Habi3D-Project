export function getPresetsByDomain(domain: CatalogDomain | 'all'): FurnitureCatalogPreset[] {
  if (domain === 'all') return CATALOG_PRESETS;
  return CATALOG_PRESETS.filter((p) => p.domain === domain);
}

export function getPresetsForRoom(roomId: string): FurnitureCatalogPreset[] {
  return CATALOG_PRESETS.filter((p) => p.defaultRoomId === roomId);
}
